#!/usr/bin/env python3
"""Reproduce the shared vector bird from the supplied PNG's 50% alpha outline.

Pixel-edge contours retain the native silhouette exactly. Transparent canvas
padding is replaced by the existing header frame using one uniform scale.
Only redundant collinear vertices are removed; no smoothing is applied.
"""
import argparse
from collections import defaultdict
from fractions import Fraction
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('archive/legacy-sources/header-icon-original-hires.png')


def contours_from_mask(mask):
    width, height = mask.size
    data = mask.tobytes()
    edges = defaultdict(list)
    for y in range(height):
        for x in range(width):
            pos = y * width + x
            if not data[pos]:
                continue
            if y == 0 or not data[pos - width]:
                edges[x, y].append((x + 1, y))
            if x == width - 1 or not data[pos + 1]:
                edges[x + 1, y].append((x + 1, y + 1))
            if y == height - 1 or not data[pos + width]:
                edges[x + 1, y + 1].append((x, y + 1))
            if x == 0 or not data[pos - 1]:
                edges[x, y + 1].append((x, y))
    if any(len(targets) != 1 for targets in edges.values()):
        raise ValueError('Ambiguous diagonal contour; inspect the source topology')
    contours = []
    while edges:
        start = next(iter(edges))
        vertices, point = [start], start
        while True:
            point = edges.pop(point)[0]
            if point == start:
                break
            vertices.append(point)
        keep = []
        for index, point in enumerate(vertices):
            before, after = vertices[index - 1], vertices[(index + 1) % len(vertices)]
            if ((point[0] - before[0]) * (after[1] - point[1])
                    != (point[1] - before[1]) * (after[0] - point[0])):
                keep.append(point)
        contours.append(keep)
    return contours


def render():
    source = ROOT / SOURCE
    with Image.open(source) as image:
        if image.mode != 'RGBA':
            raise ValueError('The original logo must retain its RGBA alpha channel')
        size = list(image.size)
        mask = image.getchannel('A').point(lambda alpha: 255 if alpha >= 128 else 0)
    bbox = mask.getbbox()
    if bbox is None:
        raise ValueError('The original logo has no foreground')
    left, top, right, bottom = bbox
    scale = Fraction(130, bottom - top)
    tx = Fraction(80) - scale * Fraction(left + right, 2)
    ty = Fraction(4) - scale * top
    if (right - left) * scale > 160:
        raise ValueError('The source aspect ratio does not fit the header frame')
    contours = contours_from_mask(mask)

    def number(value):
        return format(float(value), '.12f').rstrip('0').rstrip('.') if value else '0'

    transformed = [[(scale * x + tx, scale * y + ty) for x, y in path]
                   for path in contours]
    svg_paths = ['M' + ' L'.join(number(x) + ' ' + number(y) for x, y in path) + ' Z'
                 for path in transformed]
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="160pt" height="139pt" '
           'viewBox="0 0 160 139"><path fill="currentColor" fill-rule="nonzero" d="'
           + ' '.join(svg_paths) + '"/></svg>\n')
    tex = [
        '% Generated by scripts/generate_header_icon.py from the supplied PNG alpha>=128.',
        '% Exact native pixel-edge silhouette; common SVG/TikZ coordinates.',
        '% Uniform scale preserves the aspect ratio and the existing visible header height.',
        r'\begin{tikzpicture}[x=1bp,y=-1bp,baseline=(current bounding box.south)]',
        r'  \path[use as bounding box] (0,0) rectangle (160,139);',
        r'  \path[fill=BookPrimary,draw=none,nonzero rule]',
    ]
    for path in transformed:
        points = ['(' + number(x) + ',' + number(y) + ')' for x, y in path]
        for index in range(0, len(points), 6):
            tex.append(('    ' if index == 0 else '    -- ')
                       + ' -- '.join(points[index:index + 6]))
        tex.append('    -- cycle')
    tex[-1] += ';'
    tex.append(r'\end{tikzpicture}%')
    geometry = {
        'schema_version': 1,
        'source_path': SOURCE.as_posix(),
        'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'source_size': size,
        'source_alpha_threshold': 128,
        'source_ink_bbox': list(bbox),
        'source_ink_pixels': mask.histogram()[255],
        'frame_size': [160, 139],
        'frame_ink_bbox': [float(scale * left + tx), 4,
                           float(scale * right + tx), 134],
        'source_to_frame': {'scale': float(scale), 'translate': [float(tx), float(ty)]},
        'contours': len(contours),
        'vertices': sum(map(len, contours)),
        'method': 'alpha>=128 exact pixel-edge contours; collinear simplification only',
    }
    return {'assets/header-icon.svg': svg,
            'assets/header-icon.tex': '\n'.join(tex) + '\n',
            'assets/header-icon-geometry.json': json.dumps(geometry, indent=2) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check without changing files')
    args = parser.parse_args()
    stale = False
    for name, content in render().items():
        path = ROOT / name
        if args.check:
            valid = path.exists() and path.read_text(encoding='utf-8') == content
            print(('OK ' if valid else 'OUT OF SYNC ') + name)
            stale |= not valid
        else:
            path.write_text(content, encoding='utf-8')
            print('WROTE ' + name)
    return int(stale)


if __name__ == '__main__':
    raise SystemExit(main())
